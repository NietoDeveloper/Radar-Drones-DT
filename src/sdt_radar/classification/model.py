"""Micro-Doppler classifier: standardised features -> multinomial logistic regression (numpy inference).

Inference needs only numpy. Training uses scipy (L-BFGS) on synthetic data generated by
``microdoppler.synth_*``. The ``Classifier`` interface is deliberately tiny so a CNN over
range-Doppler maps or spectrograms (ONNX / PyTorch) can replace it without touching the pipeline.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import _DataclassT
class Classifier(Protocol):
    classes: tuple[TargetClass, ...]

    # --------------------------------------------------------------------------- inference
    def predict_proba_features(self, feats: NDArray[np.float64]) -> NDArray[np.float64]:
        z = (np.atleast_2d(feats) - self.mean) / self.std
        out = _softmax(_expand(z) @ self.W + self.b)
        return np.asarray(out[0] if np.ndim(feats) == 1 else out)

    def predict_proba(self, iq: NDArray, prf_hz: float) -> NDArray[np.float64]:
        return self.predict_proba_features(md_features(iq, prf_hz))

    # ------------------------------------------------------------------------------ io
    def save(self, path: str | Path) -> None:
        np.savez(path, mean=self.mean, std=self.std, W=self.W, b=self.b, version=self.version,
                 classes=np.array([c.value for c in self.classes]), features=np.array(FEATURE_NAMES))

    @classmethod
    def load(cls, path: str | Path) -> MicroDopplerClassifier:
        d = np.load(path, allow_pickle=False)
        names = tuple(str(x) for x in d["features"])
        if names != FEATURE_NAMES:
            raise ValueError("model was trained with a different feature set")
        return cls(d["mean"], d["std"], d["W"], d["b"], str(d["version"]),
                   tuple(TargetClass(str(c)) for c in d["classes"]))

    # -------------------------------------------------------------------------- training
    @classmethod
    def fit(cls, x: NDArray[np.float64], y: NDArray[np.int_], l2: float = 1e-2) -> MicroDopplerClassifier:
        mean, std = x.mean(axis=0), x.std(axis=0) + 1e-9
        phi = _expand((x - mean) / std)
        n, d = phi.shape
        k = len(CLASSES)
        onehot = np.eye(k)[y]

        def loss(theta: NDArray[np.float64]) -> tuple[float, NDArray[np.float64]]:
            w = theta[: d * k].reshape(d, k)
            bb = theta[d * k :]
            p = _softmax(phi @ w + bb)
            ll = -np.log(np.clip(p[np.arange(n), y], 1e-12, 1.0)).mean() + 0.5 * l2 * (w * w).sum()
            g = (p - onehot) / n
            return float(ll), np.concatenate([(phi.T @ g + l2 * w).ravel(), g.sum(axis=0)])

        res = minimize(loss, np.zeros(d * k + k), jac=True, method="L-BFGS-B", options={"maxiter": 500})
        theta = res.x
        return cls(mean, std, theta[: d * k].reshape(d, k), theta[d * k :])


def make_dataset(
    n_per_class: int, seed: int, n_samples: int = 1024, prfs: tuple[float, ...] = (10_240.0, 16_384.0)
) -> tuple[NDArray[np.float64], NDArray[np.int_]]:
    """Synthetic labelled snippets with randomised physical and radar parameters."""
    rng = np.random.default_rng(seed)
    xs, ys = [], []
    generators: tuple[Callable[..., Any], ...] = (synth_multirotor, synth_bird, synth_clutter)
    for label, fn in enumerate(generators):
        for _ in range(n_per_class):
            prf = float(rng.choice(prfs))
            v = float(rng.uniform(-15, 15))
            snr = float(rng.uniform(4, 25))
            xs.append(md_features(fn(rng, n_samples, prf, 10e9, v, snr), prf))
            ys.append(label)
    return np.array(xs), np.array(ys)


def train_default(seed: int = 7, n_per_class: int = 700) -> tuple[MicroDopplerClassifier, dict[str, float]]:
    x, y = make_dataset(n_per_class, seed)
    model = MicroDopplerClassifier.fit(x, y)
    xt, yt = make_dataset(300, seed + 1000)
    pred = model.predict_proba_features(xt).argmax(axis=1)
    acc = float((pred == yt).mean())
    per_class = {c.value: float((pred[yt == i] == i).mean()) for i, c in enumerate(CLASSES)}
    return model, {"accuracy": acc, **{f"recall_{k}": v for k, v in per_class.items()}}


def load_default_classifier() -> MicroDopplerClassifier:
    if not DEFAULT_MODEL.exists():
        model, _ = train_default()
        model.save(DEFAULT_MODEL)
        return model
    return MicroDopplerClassifier.load(DEFAULT_MODEL)
